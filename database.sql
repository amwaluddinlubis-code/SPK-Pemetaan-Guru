CREATE DATABASE IF NOT EXISTS peta_asn
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE peta_asn;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  email_verified_at TIMESTAMP NULL,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'guru',
  guru_id BIGINT UNSIGNED NULL,
  sekolah_id BIGINT UNSIGNED NULL,
  kecamatan VARCHAR(100) NULL,
  remember_token VARCHAR(100) NULL,
  created_at TIMESTAMP NULL, updated_at TIMESTAMP NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS guru (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nip VARCHAR(30) NOT NULL UNIQUE,
  nama VARCHAR(100) NOT NULL,
  mapel VARCHAR(50) NOT NULL,
  jenjang VARCHAR(10) NOT NULL,
  domisili_alamat VARCHAR(255) NOT NULL,
  kecamatan VARCHAR(100) NULL,
  sekolah_id BIGINT UNSIGNED NULL,
  domisili_lat DECIMAL(10,7) NOT NULL,
  domisili_lng DECIMAL(10,7) NOT NULL,
  sekolah_saat_ini VARCHAR(100) NOT NULL,
  sekolah_saat_ini_lat DECIMAL(10,7) NULL,
  sekolah_saat_ini_lng DECIMAL(10,7) NULL,
  created_at TIMESTAMP NULL, updated_at TIMESTAMP NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS sekolah (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  npsn VARCHAR(20) NOT NULL UNIQUE,
  nama VARCHAR(100) NOT NULL,
  alamat VARCHAR(255) NOT NULL,
  kecamatan VARCHAR(100) NULL,
  lat DECIMAL(10,7) NOT NULL,
  lng DECIMAL(10,7) NOT NULL,
  created_at TIMESTAMP NULL, updated_at TIMESTAMP NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS kebutuhan_guru (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  sekolah_id BIGINT UNSIGNED NOT NULL,
  mapel VARCHAR(50) NOT NULL,
  jumlah INT UNSIGNED NOT NULL DEFAULT 1,
  created_at TIMESTAMP NULL, updated_at TIMESTAMP NULL,
  UNIQUE KEY unik_sekolah_mapel (sekolah_id, mapel),
  CONSTRAINT fk_kebutuhan_sekolah FOREIGN KEY (sekolah_id)
    REFERENCES sekolah (id) ON DELETE CASCADE
) ENGINE=InnoDB;

